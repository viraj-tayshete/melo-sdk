#!/usr/bin/env python3
"""
Generate an Arduino sketch from docs/CAPABILITY_MODEL.json, the way the Melo
Blocks code generator will: every capability's 'codegen' template is filled
with its default inputs (every value of an enum input is used once).

Compiling the result proves that every block produces code that builds.

Usage: tools/generate_test_sketch.py OUTPUT_DIR
Writes OUTPUT_DIR/<dirname>.ino, creating the folder if needed.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def literal(inp):
    if inp["type"] == "bool":
        return ["true", "false"]
    if inp["type"] == "enum":
        return [v["code"] for v in inp["values"]]
    value = inp.get("default", inp["min"])
    return [str(value)]


def combos(inputs):
    """Every combination of literal values (bounded: enums have at most 3 values)."""
    result = [{}]
    for inp in inputs:
        result = [dict(r, **{inp["name"]: v}) for r in result for v in literal(inp)]
    return result


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    out_dir = Path(sys.argv[1])
    model = json.loads((ROOT / "docs" / "CAPABILITY_MODEL.json").read_text(encoding="utf8"))["meloCapabilityModel"]

    lines = ["// Generated by tools/generate_test_sketch.py - do not edit.",
             "#include <Melo.h>", "", "void setup() {", "    Melo.begin();", ""]
    count = 0
    for cap in model["capabilities"]:
        if cap["id"] == "END_PROGRAM":
            continue  # never returns; added last
        for values in combos(cap["inputs"]):
            code = cap["codegen"]
            for name, value in values.items():
                code = code.replace("{" + name + "}", value)
            lines.append(f"    // {cap['blockLabel']}")
            if cap["outputs"]:
                lines.append(f"    {{ auto result = {code}; (void)result; }}")
            else:
                lines.append("    " + code)
            count += 1
    lines += ["", "    Melo.halt();", "}", "", "void loop() {", "}", ""]

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"{out_dir.name}.ino").write_text("\n".join(lines), encoding="utf8")
    print(f"Wrote {out_dir / (out_dir.name + '.ino')} ({count} generated statements)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
